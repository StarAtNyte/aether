const UNKNOWN = '#####|#...#|#...#|#...#|#...#|#...#|#####';

/** Glyph rows (top first) of a character. */
export function glyph(ch: string): readonly string[] {
  return (G[ch.toUpperCase()] ?? UNKNOWN).split('|');
}

/**
 * Pixel rows (top first, '#' filled) of a text line: 5-pixel glyphs with
 * one empty column between them.
 */
export function textRows(text: string): string[] {
  const rows = ['', '', '', '', '', '', ''];
  const chars = [...text];
  chars.forEach((ch, i) => {
    const g = glyph(ch);
    for (let r = 0; r < 7; r++) rows[r] += (g[r] ?? '.....') + (i < chars.length - 1 ? '.' : '');
  });
  return rows;
}
