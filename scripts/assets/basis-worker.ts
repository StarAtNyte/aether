/**
 * The Basis Universal transcoder worker as a static file (`apps/studio/public/basis/ktx2-worker.js`).
 *
 * three's `KTX2Loader` builds its worker at run time from the transcoder's JavaScript glue and starts it
 * from a `blob:` URL. A blob worker inherits the page's Content-Security-Policy, and the glue (Emscripten
 * embind) compiles its bindings with `new Function`, which the page's policy forbids (no `'unsafe-eval'`).
 * So the same worker body is written here as an ordinary same-origin script that is served with its own
 * locked-down policy (`script-src 'self' 'unsafe-eval' 'wasm-unsafe-eval'`, nothing else: no network, no
 * nested workers), exactly like the generator sandbox worker; the page keeps its strict policy.
 *
 *   npx tsx scripts/assets/basis-worker.ts          # (re)write the worker and copy the transcoder files
 *   npx tsx scripts/assets/basis-worker.ts --check  # exit 1 when they are out of date with three
 *
 * A unit test fails when three is upgraded and the files were not regenerated.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { KTX2Loader } from 'three/addons/loaders/KTX2Loader.js';

const ROOT = resolve(import.meta.dirname, '../..');
/** Where three ships the transcoder. */
export const THREE_BASIS = join(ROOT, 'node_modules', 'three', 'examples', 'jsm', 'libs', 'basis');
/** Where the studio serves it. */
export const PUBLIC_BASIS = join(ROOT, 'apps', 'studio', 'public', 'basis');
/** File name of the worker. */
export const WORKER_FILE = 'ktx2-worker.js';

interface Ktx2LoaderStatics {
  BasisWorker: () => void;
  EngineFormat: Record<string, unknown>;
  EngineType: Record<string, unknown>;
  TranscoderFormat: Record<string, unknown>;
  BasisFormat: Record<string, unknown>;
}

/** The worker source three's KTX2Loader would put in its blob, for `transcoderJs` (the transcoder glue). */
export function basisWorkerSource(transcoderJs: string): string {
  const k = KTX2Loader as unknown as Ktx2LoaderStatics;
  const fn = k.BasisWorker.toString();
  return [
    '/* Basis Universal transcoder worker for three.js KTX2Loader (Apache-2.0 transcoder, MIT loader). Generated by scripts/assets/basis-worker.ts — do not edit. */',
    '/* constants */',
    `let _EngineFormat = ${JSON.stringify(k.EngineFormat)}`,
    `let _EngineType = ${JSON.stringify(k.EngineType)}`,
    `let _TranscoderFormat = ${JSON.stringify(k.TranscoderFormat)}`,
    `let _BasisFormat = ${JSON.stringify(k.BasisFormat)}`,
    '/* basis_transcoder.js */',
    transcoderJs,
    '/* worker */',
    fn.substring(fn.indexOf('{') + 1, fn.lastIndexOf('}')),
  ].join('\n');
}

/** Files that should be in the studio's `public/basis/` and their expected contents. */
export function expectedBasisFiles(): Map<string, Buffer> {
  const js = readFileSync(join(THREE_BASIS, 'basis_transcoder.js'));
  return new Map([
    ['basis_transcoder.js', js],
    ['basis_transcoder.wasm', readFileSync(join(THREE_BASIS, 'basis_transcoder.wasm'))],
    [WORKER_FILE, Buffer.from(basisWorkerSource(js.toString('utf8')))],
  ]);
}

function main(): void {
  const check = process.argv.includes('--check');
  const stale: string[] = [];
  mkdirSync(PUBLIC_BASIS, { recursive: true });
  for (const [name, data] of expectedBasisFiles()) {
    const out = join(PUBLIC_BASIS, name);
    const same = existsSync(out) && readFileSync(out).equals(data);
    if (same) continue;
    stale.push(name);
    if (!check) {
      if (name === WORKER_FILE) writeFileSync(out, data);
      else copyFileSync(join(THREE_BASIS, name), out);
    }
  }
  console.log(stale.length === 0 ? 'basis files up to date' : `${check ? 'out of date' : 'wrote'}: ${stale.join(', ')}`);
  if (check && stale.length > 0) process.exitCode = 1;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) main();
