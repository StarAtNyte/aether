/** Publish settings of a template kind (a slug without a row). */
export function publishForKind(kind: string | undefined): TemplatePublish {
  return kind === 'game' ? GAME : kind === 'architecture' ? WALK : SHOW;
}

/** Publish settings of `slug` (its row, else by its kind). */
export function templatePublish(slug: string, kind?: string): TemplatePublish {
  return Object.prototype.hasOwnProperty.call(TEMPLATE_PUBLISH, slug) ? (TEMPLATE_PUBLISH[slug] as TemplatePublish) : publishForKind(kind);
}
